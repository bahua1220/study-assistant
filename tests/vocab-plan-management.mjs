async function fetchState() {
  return page.evaluate(async user => {
    const { db } = await import('/src/db/index.ts')
    return { plans: await db.vocabPlans.where('ownerId').equals(user.id).toArray(), rounds: await db.vocabSessions.where('ownerId').equals(user.id).toArray(), coins: await db.coinRecords.where('ownerId').equals(user.id).count(), cards: JSON.stringify(await db.vocabCards.toArray()), logs: JSON.stringify(await db.reviewLogs.toArray()), attempts: JSON.stringify(await db.vocabAttempts.toArray()) }
  }, user)
}
